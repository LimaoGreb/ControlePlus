const fs = require('fs');
const path = require('path');

const BANKS_DIR = path.join(__dirname, '../assets/banks');
const OUTPUT = path.join(__dirname, '../src/data/bankLogos.js');

const BANK_IDS = ['nubank','c6','inter','picpay','itau','bradesco','santander','bb','caixa','neon','next','pagbank','mercadopago','sicoob','recargapay','pix','debito','telegram'];

function cleanSvg(raw) {
  return raw
    .replace(/<\?xml[^?]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<metadata[\s\S]*?<\/metadata>/g, '')
    .replace(/<sodipodi:[^>]*\/>/g, '')
    .replace(/<sodipodi:[\s\S]*?<\/sodipodi:[^>]*>/g, '')
    .replace(/\s+xmlns:sodipodi="[^"]*"/g, '')
    .replace(/\s+xmlns:inkscape="[^"]*"/g, '')
    .replace(/\s+xmlns:rdf="[^"]*"/g, '')
    .replace(/\s+xmlns:cc="[^"]*"/g, '')
    .replace(/\s+xmlns:dc="[^"]*"/g, '')
    .replace(/\s+xmlns:svg="[^"]*"/g, '')
    .replace(/\s+sodipodi:[a-zA-Z:_-]*="[^"]*"/g, '')
    .replace(/\s+inkscape:[a-zA-Z:_-]*="[^"]*"/g, '')
    .replace(/\s+xml:space="[^"]*"/g, '')
    .replace(/\s{2,}/g, ' ')
    .replace(/>\s+</g, '><')
    .trim();
}

const lines = ["// Auto-generated by scripts/generate-bank-logos.js — do not edit manually", ""];

for (const id of BANK_IDS) {
  const file = path.join(BANKS_DIR, `${id}.svg`);
  if (!fs.existsSync(file)) {
    console.warn(`AVISO: ${id}.svg não encontrado`);
    continue;
  }
  const raw = fs.readFileSync(file, 'utf8');
  const cleaned = cleanSvg(raw);
  lines.push(`export const ${id} = \`${cleaned.replace(/`/g, "'")}\`;`);
  lines.push('');
  console.log(`✓ ${id}`);
}

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, lines.join('\n'), 'utf8');
console.log(`\nGerado: ${OUTPUT}`);
